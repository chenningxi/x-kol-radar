CREATE TABLE IF NOT EXISTS xkol_profiles (
 handle VARCHAR(32) PRIMARY KEY,
 config JSON NOT NULL,
 cursor_id VARCHAR(32) NULL,
 updated_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS xkol_tweets (
 tweet_id VARCHAR(32) PRIMARY KEY,
 url VARCHAR(255) NOT NULL UNIQUE,
 profile_handle VARCHAR(32) NOT NULL,
 payload JSON NOT NULL,
 translation_status VARCHAR(32) NOT NULL DEFAULT 'pending',
 content_policy_version VARCHAR(32) NULL,
 revision BIGINT NOT NULL DEFAULT 1,
 first_seen_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP(6),
 updated_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 INDEX idx_profile(profile_handle),
 INDEX idx_translation(translation_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS xkol_receipts (
 event_key CHAR(64) PRIMARY KEY,
 tweet_url VARCHAR(255) NOT NULL,
 status VARCHAR(32) NOT NULL,
 payload JSON NOT NULL,
 recorded_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP(6),
 INDEX idx_receipt(tweet_url,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS xkol_sync_history (
 event_key CHAR(64) PRIMARY KEY,
 payload JSON NOT NULL,
 recorded_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS xkol_batches (
 batch_key CHAR(64) PRIMARY KEY,
 payload JSON NOT NULL,
 status VARCHAR(32) NOT NULL DEFAULT 'pending',
 updated_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
